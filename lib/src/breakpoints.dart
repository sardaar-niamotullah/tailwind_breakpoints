/// Default Tailwind-style breakpoint widths, in logical pixels.
abstract final class Breakpoints {
  /// Extra small: 480 logical pixels.
  static const double xs = 480;

  /// Small: 640 logical pixels.
  static const double sm = 640;

  /// Medium: 768 logical pixels.
  static const double md = 768;

  /// Large: 1024 logical pixels.
  static const double lg = 1024;

  /// Extra large: 1280 logical pixels.
  static const double xl = 1280;

  /// 2x extra large: 1536 logical pixels.
  static const double xxl = 1536;
}
